using System;

class Program
{
    static void Main()
    {
        // Número entero
        int edad = 30;

        // Número decimal
        double altura = 1.78;

        // Un solo carácter
        char inicial = 'J';

        // Cadena de texto
        string nombre = "Jonatan";

        // Valor verdadero o falso
        bool trabaja = true;

        Console.WriteLine("=== TIPOS DE DATOS ===\n");

        Console.WriteLine($"Nombre: {nombre}");
        Console.WriteLine($"Edad: {edad}");
        Console.WriteLine($"Altura: {altura}");
        Console.WriteLine($"Inicial: {inicial}");
        Console.WriteLine($"¿Trabaja?: {trabaja}");
    }
}
